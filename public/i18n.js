export function resolveLanguage(preference, systemLanguage = '') {
  if (preference === 'zh' || preference === 'en') return preference;
  const system = String(systemLanguage).trim().toLowerCase();
  return system.startsWith('zh') ? 'zh' : 'en';
}

export function detectSystemLanguage() {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale || '';
  } catch {
    return '';
  }
}

export function t(lang, key, params = {}) {
  const catalog = MESSAGES[lang] ?? MESSAGES.en;
  const template = catalog[key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined || params[name] === null ? match : String(params[name])
  );
}

export function formatWarning(lang, warning) {
  if (!warning) return '';
  if (typeof warning === 'string') return warning;
  return t(lang, `warning.${warning.code}`, warning.params ?? {});
}
